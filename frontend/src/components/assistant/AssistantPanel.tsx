import { useQuery } from '@tanstack/react-query'
import { Link } from '@tanstack/react-router'
import { Maximize2, MessageSquarePlus, X } from 'lucide-react'
import { useState } from 'react'
import { assistantStatusOptions } from '@/api/generated/@tanstack/react-query.gen'
import { ChatView } from '@/components/assistant/ChatView'
import { Button } from '@/components/ui/button'

/**
 * Docked chat panel, toggled from the header. It's the same chat as the Explore page:
 * conversations are saved, and "Open in Explore" continues this one full-screen.
 *
 * The chat UI under components/assistant-ui/ was generated by
 * `npx assistant-ui@latest add thread` and is yours to edit like shadcn components.
 */
export function AssistantPanel({ onClose }: { onClose: () => void }) {
  const status = useQuery(assistantStatusOptions())
  const [threadId, setThreadId] = useState<number | null>(null)
  const [chatKey, setChatKey] = useState(0)

  return (
    <aside className="flex h-full w-full flex-col border-l bg-background">
      <div className="flex items-center gap-1 border-b px-4 py-2">
        <span className="font-semibold">Assistant</span>
        {status.data && (
          <span className="ml-1 text-xs text-muted-foreground">
            {status.data.configured ? status.data.model : 'no API key set'}
          </span>
        )}
        <div className="ml-auto flex">
          <Button
            variant="ghost"
            size="icon"
            className="h-8 w-8"
            aria-label="New chat"
            title="New chat"
            onClick={() => {
              setThreadId(null)
              setChatKey((k) => k + 1)
            }}
          >
            <MessageSquarePlus className="h-4 w-4" />
          </Button>
          <Button variant="ghost" size="icon" className="h-8 w-8" aria-label="Open in Explore" title="Open in Explore" asChild>
            <Link to="/explore" search={threadId ? { t: threadId } : {}} onClick={onClose}>
              <Maximize2 className="h-4 w-4" />
            </Link>
          </Button>
          <Button variant="ghost" size="icon" className="h-8 w-8" onClick={onClose} aria-label="Close assistant">
            <X className="h-4 w-4" />
          </Button>
        </div>
      </div>

      {status.data && !status.data.configured && (
        <p className="border-b bg-amber-50 px-4 py-2 text-xs text-amber-900 dark:bg-amber-950 dark:text-amber-200">
          Set <code>OPENAI_API_KEY</code> in <code>backend/.env</code> and restart the API to enable chat.
        </p>
      )}

      <div className="min-h-0 flex-1">
        {/* The panel keeps its chat mounted after the thread is created, so no reload */}
        <ChatView key={chatKey} threadId={null} onThreadCreated={setThreadId} />
      </div>
    </aside>
  )
}
